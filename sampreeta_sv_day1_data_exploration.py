import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns

# 1. Create a dataset with at least 10 rows

data = {
    "Hours_Studied": [2, 5, 3, 7, 1, 6, 4, 8, 5, 3],
    "Attendance": [60, 90, 75, 95, 50, 88, 80, 98, 85, 70],
    "Previous_Score": [45, 70, 55, 82, 40, 78, 65, 90, 72, 58],
    "Final_Score": [42, 76, 58, 88, 35, 82, 68, 94, 79, 60]
}

df = pd.DataFrame(data)

# 2. Display first 5 rows and dataset shape

print("FIRST 5 ROWS:")
print(df.head())

print("\nDATASET SHAPE:")
print(df.shape)

# 3. Check data types and missing values

print("\nDATA TYPES:")
print(df.dtypes)

print("\nMISSING VALUES:")
print(df.isnull().sum())

# 4. Identify unusual values and data quality issues

print("\nDUPLICATE ROWS:")
print(df.duplicated().sum())

print("\nUNUSUAL VALUES:")
print("Hours outside 0-24:",
      ((df["Hours_Studied"] < 0) | (df["Hours_Studied"] > 24)).sum())

print("Attendance outside 0-100:",
      ((df["Attendance"] < 0) | (df["Attendance"] > 100)).sum())

print("Final scores outside 0-100:",
      ((df["Final_Score"] < 0) | (df["Final_Score"] > 100)).sum())

# 5. Create a chart

plt.figure(figsize=(8, 5))

sns.barplot(
    data=df,
    x="Hours_Studied",
    y="Final_Score"
)

plt.title("Study Hours vs Final Score")
plt.xlabel("Hours Studied")
plt.ylabel("Final Score")

plt.show()

# 6. Write three observations

print("\nTHREE OBSERVATIONS:")

print("1. Students who studied more hours generally scored higher.")

print("2. Students with higher attendance generally achieved better scores.")

print("3. The highest final score is 94, achieved by a student who studied 8 hours.")

# Conclusion

print("\nCONCLUSION:")
print("The dataset shows a positive relationship between study hours")
print("and final scores. Attendance also plays an important role")
print("in student academic performance.")